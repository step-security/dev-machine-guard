// swiftWriteGoldenFixture adds the remaining contract cases to the scan
// fixture: lock schema variants, a v1 lock beside a renamed mirror, a local
// artifact without checksum, legacy and process configuration, all findings,
// a malformed lock and search roots that are empty or absent.
func swiftWriteGoldenFixture(t *testing.T, home, root string) {
	t.Helper()
	swiftWriteFixture(t, home, root)
	lab := filepath.Join(home, "lab")

	mirrored := filepath.Join(root, "mirrored")
	goWrite(t, filepath.Join(mirrored, "Package.swift"), "", 0o600)
	swiftCopy(t, "resolved-v1-mirror.json", filepath.Join(mirrored, "Package.resolved"), lab)
	swiftCopy(t, "workspace-v1-mirror.json", filepath.Join(mirrored, ".build", "workspace-state.json"), lab)
	swiftDir(t, filepath.Join(mirrored, ".build", "checkouts", "RenamedAlgorithms"))
	goWrite(t, filepath.Join(mirrored, ".swiftpm", "config"), `{"object":[{"original":"https://github.com/apple/swift-algorithms.git","mirror":"https://deploy:CANARY_TOKEN@mirror.example.invalid/algorithms.git"}],"version":1}`, 0o600)

	tool := filepath.Join(root, "tool")
	goWrite(t, filepath.Join(tool, "Package.swift"), "", 0o600)
	swiftCopy(t, "resolved-v2.json", filepath.Join(tool, "Package.resolved"), lab)
	swiftCopy(t, "workspace-local-artifact.json", filepath.Join(tool, ".build", "workspace-state.json"), lab)
	plugin := filepath.Join(lab, "third-pass-20261105", "reference", "Fixtures", "Miscellaneous", "Plugins", "MyBinaryToolPlugin")
	swiftDir(t, filepath.Join(plugin, "Binaries", "MyVendedSourceGenBuildTool.artifactbundle"))

	registry := filepath.Join(root, "registry-app")
	goWrite(t, filepath.Join(registry, "Package.swift"), "", 0o600)
	swiftCopy(t, "resolved-registry.json", filepath.Join(registry, "Package.resolved"), lab)
	swiftCopy(t, "registries-security.json", filepath.Join(registry, ".swiftpm", "configuration", "registries.json"), lab)

	broken := filepath.Join(root, "broken")
	goWrite(t, filepath.Join(broken, "Package.swift"), "", 0o600)
	goWrite(t, filepath.Join(broken, "Package.resolved"), `{"version":3,"pins":[{"identity":"half"`, 0o600)

	swiftDir(t, filepath.Join(home, "empty"))
	goWrite(t, filepath.Join(home, "ci", "mirrors.json"), string(swiftFixture(t, "mirrors-modern.json")), 0o600)
}

// The shared contract is generated by the real guarded scanner over the
// fixture tree. Host-specific paths and the IDs derived from them are normalized.
func TestSwiftGoldenProducer(t *testing.T) {
	if runtime.GOOS == model.PlatformWindows {
		t.Skip("canonical Unix fixture; wire round-trip and scanner tests also run on Windows")
	}
	home := goTestHome(t)
	root := filepath.Join(home, "projects")
	swiftWriteGoldenFixture(t, home, root)
	scanner, x := swiftTestScanner(t, home, model.PlatformDarwin)
	scanner.protection = swiftTCC(home)
	x.env["SWIFTPM_MIRROR_CONFIG"] = filepath.Join(home, "ci", "mirrors.json")
	inv, audit := scanner.Scan(context.Background(), goTestTarget(home), []string{root, filepath.Join(home, "empty"), filepath.Join(home, "missing")}, nil)
	swiftAssertRefs(t, inv)
	type sections struct {
		Inventory *model.SwiftInventory   `json:"swift_inventory"`
		Audit     *model.SwiftConfigAudit `json:"swift_config_audit"`
	}
	pair := sections{inv, audit}
	raw, err := json.Marshal(pair)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Contains(raw, []byte("CANARY")) {
		t.Fatal("canary reached the wire")
	}
	raw = []byte(strings.ReplaceAll(string(raw), home, "/Users/swift-fixture"))
	if err := json.Unmarshal(raw, &pair); err != nil {
		t.Fatal(err)
	}
	user := goTestTarget(home).Username
	replacements := []string{}
	for _, s := range pair.Inventory.Sources {
		replacements = append(replacements, s.SourceID, configaudit.GoSourceID(user, s.Kind, s.Path))
	}
	for _, f := range pair.Audit.Files {
		replacements = append(replacements, f.SourceID, configaudit.GoSourceID(user, "swift_config_"+f.Scope, f.Path))
	}
	raw = []byte(strings.NewReplacer(replacements...).Replace(string(raw)))
	pair = sections{}
	if err := json.Unmarshal(raw, &pair); err != nil {
		t.Fatal(err)
	}
	for i := range pair.Inventory.Sources {
		slices.Sort(pair.Inventory.Sources[i].DiscoveredSources)
	}
	a := pair.Audit
	slices.SortFunc(a.Findings, func(x, y model.CargoConfigFinding) int {
		return strings.Compare(x.Code+"\x00"+x.SourceID+"\x00"+x.Key, y.Code+"\x00"+y.SourceID+"\x00"+y.Key)
	})
	slices.SortFunc(a.Contexts, func(x, y model.RubyConfigContext) int {
		return strings.Compare(x.ProjectPath+"\x00"+strings.Join(x.ConfigSourceIDs, ","), y.ProjectPath+"\x00"+strings.Join(y.ConfigSourceIDs, ","))
	})
	swiftAssertRefs(t, pair.Inventory)
	raw, err = json.MarshalIndent(pair, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	raw = append(raw, '\n')
	path := "../model/testdata/swift_inventory_v1_golden.json"
	if os.Getenv("UPDATE_SWIFT_GOLDEN") == "1" {
		if err := os.WriteFile(path, raw, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(raw, want) {
		t.Fatal("producer differs from shared Swift golden; review the contract before regenerating")
	}
}
